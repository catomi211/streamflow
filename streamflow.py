plt.ylabel("Births")

# this finds the index of a speciifc x value using np.where. Then it finds the exact x and y values and assigns them to varibales.Do this for every date.
ny_index = np.where(x == np.datetime64("2012-01-01"))[0][0]
ny_x, ny_y = x[ny_index], y_1[ny_index]

fj_index = np.where(x == np.datetime64("2012-07-04"))[0][0]
fj_x, fj_y = x[fj_index], y_1[fj_index]

hal_index = np.where(x == np.datetime64("2012-10-31"))[0][0]
hal_x, hal_y = x[hal_index], y_1[hal_index]

thnk_index = np.where(x == np.datetime64("2012-11-22"))[0][0]
thnk_x, thnk_y = x[thnk_index], y_1[thnk_index]

chris_index = np.where(x == np.datetime64("2012-12-25"))[0][0]
chris_x, chris_y = x[chris_index], y_1[chris_index]

# this adds the arrows pointing to each point using the coordinates i found earlier. Also uses connection style to curve some of the arros to match the one in hw.
plt.annotate("New Years",xy = (ny_x,ny_y), xytext = (ny_x + np.timedelta64(25,"D"),ny_y - 100), arrowprops = dict(facecolor ="black",shrink = 0.08, width = 1.5, headwidth = 4))
plt.annotate("4th of July",xy = (fj_x,fj_y), xytext = (fj_x + np.timedelta64(20,"D"),fj_y - 10), arrowprops = dict(facecolor ="black",shrink = 0.08, width = 1.5, headwidth = 4,connectionstyle = "arc3,rad=-0.3"))
