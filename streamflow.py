import matplotlib.pyplot as plt
import numpy as np

"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

# list the variables.
L = 6
R_A = 170
R_B = 410
P_1 = 100
q_1 = 120
q_2 = 120

# instead of doing an empty array of 0 do a list and later convert it to an array
x = np.linspace(0,L,500)
v = []

# a for loop to add in each value based on the piecewise defintino
for value in x:
  if value < 2:
    v.append(R_A - (q_1 * value))

  elif 2 < value < 4:
    v.append(R_A - (q_1 *2) - P_1)

  elif value > 4:
    v.append(R_A - (q_1 * 2) - P_1 + R_B - (q_2 * (value - 4)) )

# turn the list into an array
v = np.array(v)

plt.plot(x,v, color = "purple")
plt.title("Shear Diagram")
plt.xlabel("x (ft)")

# this adds in an axis along the x axis
plt.axhline(color = "black", linewidth=1)

plt.ylabel("V (lb)")

# fills area under each curve/line
plt.fill_between(x,v,color="purple",alpha = 0.3)

plt.show()

"""### Part 1b - Moment Diagram

You will create your moment diagram in the code block below.
"""

# same process as in Part 1 a
L = 6
R_A = 170
R_B = 410
P_1 = 100
q_1 = 120
q_2 = 120

x = np.linspace(0,L,500)
y_m = []

for value in x:
  if value < 2:
    y_m.append((R_A * value) - (q_1 * ((value**2) / 2)))

  elif 2 < value < 4:
    y_m.append((R_A * value) - (q_1 * 2 * (value - 1)) - (P_1 * ( value - 2)))

  elif value > 4:
    y_m.append((R_A * value) - (q_1 * 2 * (value - 1)) - (P_1 * (value -2)) + (R_B * (value - 4)) - (q_2 * (value - 4) * ((value - 4)/2)) )

y_m = np.array(y_m)

plt.plot(x,y_m, color = "purple")
plt.title("Moment Diagram")
plt.xlabel("x (ft)")
plt.axhline(color = "black", linewidth=1)
plt.ylabel("M (lb-ft)")
plt.fill_between(x,y_m,color="purple",alpha = 0.3)

plt.show()

